import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import type { RegisterSWOptions } from 'vite-plugin-pwa/types'

const mocks = vi.hoisted(() => ({ register: vi.fn(), activate: vi.fn(), options: {} as RegisterSWOptions }))
vi.mock('virtual:pwa-register', () => ({ registerSW: mocks.register }))
let reload: ReturnType<typeof vi.fn>
beforeEach(() => {
  vi.resetModules(); vi.clearAllMocks(); vi.stubEnv('PROD', true)
  reload = vi.fn()
  const target = new EventTarget()
  vi.stubGlobal('window', Object.assign(target, { isSecureContext: true, matchMedia: () => ({ matches: false }), location: { reload }, setInterval: vi.fn() }))
  vi.stubGlobal('navigator', { onLine: true, serviceWorker: {} })
  mocks.activate.mockReset(); mocks.activate.mockResolvedValue(undefined)
  mocks.register.mockImplementation((options: RegisterSWOptions) => { mocks.options = options; return mocks.activate })
})
afterEach(() => { vi.unstubAllGlobals(); vi.unstubAllEnvs() })

describe('PWA lifecycle', () => {
  it('starts once, announces complete precache, and waits for consent to update', async () => {
    const pwa = await import('./pwa')
    pwa.startPwa(); pwa.startPwa()
    expect(mocks.register).toHaveBeenCalledTimes(1)
    expect(pwa.getPwaState().offlineReady).toBe(false)
    mocks.options.onOfflineReady?.()
    mocks.options.onNeedRefresh?.()
    expect(pwa.getPwaState()).toMatchObject({ offlineReady: true, updateReady: true, updating: false })
    expect(reload).not.toHaveBeenCalled()
    expect(mocks.activate).not.toHaveBeenCalled()
  })
  it('does not reload when another tab activates the new worker', async () => {
    const pwa = await import('./pwa'); pwa.startPwa()
    window.location.hash = '#/learn'
    mocks.options.onNeedReload?.()
    expect(reload).not.toHaveBeenCalled()
    expect(pwa.getPwaState().updateReady).toBe(true)
    expect(pwa.getPwaState().reloadNeeded).toBe(true)
    expect(pwa.getPwaState().reloadFromPath).toBe('/learn')
    await pwa.applyPwaUpdate()
    expect(reload).toHaveBeenCalledTimes(1)
    expect(mocks.activate).not.toHaveBeenCalled()
  })
  it('reloads only after an accepted local update takes control', async () => {
    const pwa = await import('./pwa'); pwa.startPwa()
    mocks.options.onNeedRefresh?.()
    await pwa.applyPwaUpdate()
    expect(mocks.activate).toHaveBeenCalledTimes(1)
    expect(reload).not.toHaveBeenCalled()
    mocks.options.onNeedReload?.()
    expect(reload).toHaveBeenCalledTimes(1)
  })
  it('reports update and registration failures without losing the working app', async () => {
    const pwa = await import('./pwa'); pwa.startPwa()
    mocks.options.onRegisterError?.(new Error('offline'))
    expect(pwa.getPwaState().error).toContain('准备失败')
    mocks.options.onNeedRefresh?.()
    mocks.activate.mockRejectedValueOnce(new Error('offline'))
    await pwa.applyPwaUpdate()
    expect(pwa.getPwaState()).toMatchObject({ updating: false, updateReady: true })
    expect(pwa.getPwaState().error).toContain('更新未完成')
    expect(reload).not.toHaveBeenCalled()
  })
  it('avoids service workers in development or insecure contexts', async () => {
    vi.stubEnv('PROD', false)
    const pwa = await import('./pwa'); pwa.startPwa()
    expect(mocks.register).not.toHaveBeenCalled()
    expect(pwa.getPwaState().supported).toBe(false)
  })
  it('retains the install prompt before the settings page is opened', async () => {
    const pwa = await import('./pwa'); pwa.startPwa()
    const prompt = vi.fn().mockResolvedValue(undefined)
    const event = Object.assign(new Event('beforeinstallprompt', { cancelable: true }), { prompt, userChoice: Promise.resolve({ outcome: 'dismissed' }) })
    window.dispatchEvent(event)
    expect(event.defaultPrevented).toBe(true)
    expect(pwa.getPwaState().canInstall).toBe(true)
    expect(await pwa.installPwa()).toContain('已取消')
    expect(prompt).toHaveBeenCalledTimes(1)
    expect(pwa.getPwaState().canInstall).toBe(false)
    window.dispatchEvent(new Event('appinstalled'))
    expect(pwa.getPwaState().installed).toBe(true)
  })
})

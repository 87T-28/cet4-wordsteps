import { render, screen, within, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { App } from './App'
import { StudyProvider } from './StudyProvider'
import { repository } from '../services/storage/database'
import { sampleWords } from '../data/sampleWords'

const words = sampleWords.slice(0, 3).map(word => ({ ...word, id: 'ecdict:' + word.text, tags: ['cet4'] }))
beforeEach(async () => {
  vi.restoreAllMocks()
  vi.stubGlobal('scrollTo', vi.fn())
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, json: async () => words }))
  await repository.db.transaction('rw', repository.db.events, repository.db.progress, repository.db.meta, async () => {
    await repository.db.events.clear(); await repository.db.progress.clear(); await repository.db.meta.clear()
  })
})
function renderPage(path = '/') { return render(<StudyProvider><MemoryRouter initialEntries={[path]}><App /></MemoryRouter></StudyProvider>) }

describe('local study application', () => {
  it('keeps all seven pages reachable', async () => {
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { level: 1, name: '今天，也向前一步。' })
    const nav = within(screen.getByRole('navigation', { name: '主要导航' }))
    for (const [label, title] of [['单词学习', '认识一个新单词'], ['复习', '让记忆更长久'], ['词库', '每一个词，都有意义。'], ['学习统计', '看见每一步的积累'], ['设置', '找到适合你的节奏'], ['账号', '随时回来，继续前进。'], ['今日学习', '今天，也向前一步。']]) {
      await user.click(nav.getByRole('link', { name: label }))
      expect(await screen.findByRole('heading', { level: 1, name: title })).toBeVisible()
      expect(nav.getByRole('link', { name: label })).toHaveAttribute('aria-current', 'page')
    }
  })
  it('saves scoring once and resumes with the next unlearned word after remount', async () => {
    const user = userEvent.setup()
    const view = renderPage('/learn')
    await screen.findByRole('heading', { name: 'achieve' })
    await user.click(screen.getByRole('button', { name: '查看释义' }))
    await user.dblClick(screen.getByRole('button', { name: /记住了/ }))
    await screen.findByText(/已保存到本机/)
    expect(await repository.listPendingEvents()).toHaveLength(1)
    view.unmount()
    renderPage('/learn')
    expect(await screen.findByRole('heading', { name: 'curious' })).toBeVisible()
  })
  it('forces failed spelling into the relearning schedule and records accuracy', async () => {
    const user = userEvent.setup()
    renderPage('/learn')
    await screen.findByRole('heading', { name: 'achieve' })
    await user.click(screen.getByRole('checkbox', { name: /拼写测试/ }))
    expect(screen.queryByRole('heading', { name: 'achieve' })).not.toBeInTheDocument()
    await user.type(screen.getByRole('textbox', { name: '英文拼写' }), 'wrong')
    await user.click(screen.getByRole('button', { name: '检查拼写' }))
    expect(screen.getByRole('button', { name: /很熟悉/ })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: /没记住/ }))
    await screen.findByText(/已保存到本机/)
    const event = (await repository.listPendingEvents())[0]
    expect(event.objectiveCorrect).toBe(false)
    expect((await repository.getProgress(event.wordId))?.mistakes).toBe(1)
    await user.click(screen.getByRole('link', { name: '学习统计' }))
    expect(await screen.findByText('0%')).toBeVisible()
  })
  it('does not report completion on storage failure and retries without duplicate events', async () => {
    const user = userEvent.setup()
    const append = vi.spyOn(repository, 'appendEvent').mockRejectedValueOnce(new Error('quota'))
    renderPage('/learn')
    await screen.findByRole('heading', { name: 'achieve' })
    await user.click(screen.getByRole('button', { name: '查看释义' }))
    await user.click(screen.getByRole('button', { name: /记住了/ }))
    expect(await screen.findByRole('alert')).toHaveTextContent('保存失败')
    expect(screen.queryByText(/已保存到本机/)).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /记住了/ }))
    await screen.findByText(/已保存到本机/)
    expect(append.mock.calls[0][0].id).toBe(append.mock.calls[1][0].id)
    expect(await repository.listPendingEvents()).toHaveLength(1)
  })
  it('searches Chinese and English, filters words, and clears no results', async () => {
    const user = userEvent.setup()
    renderPage('/dictionary')
    const search = await screen.findByRole('searchbox')
    await user.type(search, ' ACHIEVE ')
    expect(screen.getByRole('heading', { name: 'achieve' })).toBeVisible()
    expect(screen.queryByRole('heading', { name: 'curious' })).not.toBeInTheDocument()
    await user.clear(search); await user.type(search, '好奇')
    expect(screen.getByRole('heading', { name: 'curious' })).toBeVisible()
    await user.clear(search); await user.type(search, 'unknown-word')
    expect(screen.getByText('没有找到这个词')).toBeVisible()
    await user.click(screen.getByRole('button', { name: '清空搜索与筛选' }))
    expect(screen.getByRole('heading', { name: 'achieve' })).toBeVisible()
    await user.selectOptions(screen.getByRole('combobox', { name: '词库筛选' }), 'learned')
    expect(screen.getByText('没有找到这个词')).toBeVisible()
  })
  it('persists the daily plan and reloads it', async () => {
    const user = userEvent.setup()
    const view = renderPage('/settings')
    const input = await screen.findByRole('spinbutton', { name: /每日新学单词/ })
    await user.clear(input); await user.type(input, '30')
    await user.click(screen.getByRole('button', { name: '保存学习计划' }))
    await screen.findByText('学习计划已保存到本机。')
    view.unmount(); renderPage('/settings')
    expect(await screen.findByRole('spinbutton', { name: /每日新学单词/ })).toHaveValue(30)
  })
  it('defaults to encrypted exports and does not silently export without a password', async () => {
    const user = userEvent.setup()
    renderPage('/settings')
    expect(await screen.findByRole('checkbox', { name: /导出时用密码加密/ })).toBeChecked()
    await user.click(screen.getByRole('button', { name: '导出 JSON 备份' }))
    // A secure browser reports the password requirement; jsdom may lack SubtleCrypto.
    expect(await screen.findByRole('alert')).toHaveTextContent(/加密|备份密码/)
    expect(screen.queryByRole('link', { name: '点击下载备份文件' })).not.toBeInTheDocument()
  })
  it('requires explicit typed confirmation before clearing the local profile', async () => {
    const user = userEvent.setup()
    renderPage('/settings')
    await screen.findByRole('heading', { level: 1, name: '找到适合你的节奏' })
    await user.click(screen.getByText('清除本机学习档案'))
    expect(screen.getByRole('button', { name: '确认清除本机档案' })).toBeDisabled()
    await user.type(screen.getByRole('textbox', { name: '输入“清除学习记录”确认' }), '清除学习记录')
    expect(screen.getByRole('button', { name: '确认清除本机档案' })).toBeEnabled()
  })
  it('previews and confirms backup merging and rejects damaged files', async () => {
    const user = userEvent.setup()
    renderPage('/settings')
    const input = await screen.findByLabelText('选择 JSON 备份')
    const backup = { app: 'wordsteps', version: 1, exportedAt: new Date().toISOString(), settings: { dailyNewWords: 10, dailyReviewLimit: 20 }, events: [{ id: 'restore', deviceId: 'other', wordId: words[0].id, occurredAt: new Date().toISOString(), kind: 'new', rating: 'good', objectiveCorrect: true, schemaVersion: 1 }] }
    const file = new File([JSON.stringify(backup)], 'backup.json', { type: 'application/json' })
    Object.defineProperty(file, 'text', { value: async () => JSON.stringify(backup) })
    await user.upload(input, file)
    await screen.findByText('导入预览')
    expect(await repository.listPendingEvents()).toHaveLength(0)
    await user.click(screen.getByRole('button', { name: '确认合并导入' }))
    await screen.findByText(/导入完成，新增 1/)
    expect(await repository.listPendingEvents()).toHaveLength(1)
    const broken = new File(['bad'], 'broken.json', { type: 'application/json' })
    Object.defineProperty(broken, 'text', { value: async () => 'bad' })
    await user.upload(input, broken)
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('JSON'))
    expect(await repository.listPendingEvents()).toHaveLength(1)
  })
  it('reports unavailable storage and recovers after retry', async () => {
    const user = userEvent.setup()
    const read = vi.spyOn(repository, 'listProgress').mockRejectedValue(new Error('unavailable'))
    renderPage()
    expect(await screen.findByRole('alert')).toHaveTextContent('无法读取本机学习数据')
    read.mockRestore()
    await user.click(screen.getByRole('button', { name: '重新尝试' }))
    expect(await screen.findByRole('heading', { level: 1, name: '今天，也向前一步。' })).toBeVisible()
  })
  it('accepts correct spelling with case and whitespace normalization', async () => {
    const user = userEvent.setup()
    renderPage('/learn')
    await screen.findByRole('heading', { name: 'achieve' })
    await user.click(screen.getByRole('checkbox', { name: /拼写测试/ }))
    await user.type(screen.getByRole('textbox', { name: '英文拼写' }), ' ACHIEVE ')
    await user.click(screen.getByRole('button', { name: '检查拼写' }))
    expect(screen.getByText('拼写正确')).toBeVisible()
    await user.click(screen.getByRole('button', { name: /记住了/ }))
    await screen.findByText(/已保存到本机/)
    expect((await repository.listPendingEvents())[0].objectiveCorrect).toBe(true)
  })
  it('provides recovery from a missing page', async () => {
    const user = userEvent.setup()
    renderPage('/missing')
    await user.click(await screen.findByRole('link', { name: '返回今日学习' }))
    expect(await screen.findByRole('heading', { level: 1, name: '今天，也向前一步。' })).toBeVisible()
  })
})
